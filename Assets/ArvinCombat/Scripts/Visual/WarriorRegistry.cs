using System;
using System.Collections.Generic;
using UnityEngine;

namespace ArvinCombat
{
    [Serializable]
    public class WarriorVisual
    {
        public WarriorId id;
        public GameObject prefab;          // model + Animator (generated by ArvinCombat > Setup)
        public float modelScale = 1f;
        public List<string> clipKeys = new List<string>();
        public List<float> clipLengths = new List<float>();

        public float GetLength(string key, float fallback = 0.8f)
        {
            int i = clipKeys.IndexOf(key);
            return i >= 0 ? Mathf.Max(0.05f, clipLengths[i]) : fallback;
        }

        public bool Has(string key) => clipKeys.Contains(key);
    }

    /// <summary>Generated by the editor setup. Lives at Resources/ArvinCombat/WarriorRegistry.asset</summary>
    public class WarriorRegistry : ScriptableObject
    {
        public List<WarriorVisual> warriors = new List<WarriorVisual>();
        public int setupVersion; // bumped by the editor setup when warriors need rebuilding

        static WarriorRegistry _instance;
        public static WarriorRegistry Instance
        {
            get
            {
                if (_instance == null) _instance = Resources.Load<WarriorRegistry>("ArvinCombat/WarriorRegistry");
                return _instance;
            }
        }

        public WarriorVisual Get(WarriorId id)
        {
            foreach (var w in warriors) if (w.id == id) return w;
            return null;
        }
    }
}
